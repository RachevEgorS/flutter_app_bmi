import 'package:supabase_flutter/supabase_flutter.dart';

class UserProfile {
  UserProfile({
    required this.id,
    required this.name,
    required this.surname,
    required this.email,
  });
  // auth.users.id = body_mass_index_calculations.user_id.
  final String id;
  final String name;
  final String surname;
  final String email;
  String get fullName => '$name $surname'.trim();
}

class RegistrationResult {
  const RegistrationResult({
    required this.email,
    required this.requiresEmailConfirmation,
  });
  final String email;
  final bool requiresEmailConfirmation;
}

class AppSession {
  AppSession({this._client});

  final SupabaseClient? _client;
  SupabaseClient get _supabase => _client ?? Supabase.instance.client;
  UserProfile? _currentUser;
  UserProfile get user => _currentUser!;

  static const _calculations = 'body_mass_index_calculations';
  static const _recordColumns =
      'id,created_at,height,weight,body_mass_index,recommendation,user_id';

  String _requireUserId() {
    final id = _supabase.auth.currentUser?.id;
    if (id == null || id != _currentUser?.id) {
      throw const AuthException('Войдите в аккаунт заново.');
    }
    return id;
  }

  Future<BmiRecord> saveCalculation(BmiRecord record) async {
    final userId = _requireUserId();
    if (!isDatabaseMeasurement(record.height) ||
        !isDatabaseMeasurement(record.weight) ||
        !record.bmi.isFinite ||
        record.bmi <= 0) {
      throw ArgumentError(
        'Рост и вес должны быть положительными целыми числами.',
      );
    }
    final row = await _supabase
        .from(_calculations)
        .insert({
          // id and created_at are generated by the existing database defaults.
          'height': record.height.toInt(),
          'weight': record.weight.toInt(),
          'body_mass_index': record.bmi,
          'recommendation': record.recommendation,
          'user_id': userId,
        })
        .select(_recordColumns)
        .single();
    return BmiRecord.fromJson(row);
  }

  Future<List<BmiRecord>> loadHistory({int offset = 0, int limit = 50}) async {
    final userId = _requireUserId();
    final rows = await _supabase
        .from(_calculations)
        .select(_recordColumns)
        .eq('user_id', userId)
        .order('created_at', ascending: false)
        .order('id', ascending: false)
        .range(offset, offset + limit - 1);
    return rows.map(BmiRecord.fromJson).toList();
  }

  Future<void> signIn(String email, String password) async {
    final response = await _supabase.auth.signInWithPassword(
      email: email.trim().toLowerCase(),
      password: password,
    );
    final authUser = response.user;
    if (authUser == null || response.session == null) {
      throw const AuthException('Не удалось войти. Повторите попытку.');
    }
    final metadata = authUser.userMetadata ?? <String, dynamic>{};
    if (_currentUser?.id != authUser.id) {
      _currentUser = UserProfile(
        id: authUser.id,
        name: metadata['name'] as String? ?? '',
        surname: metadata['surname'] as String? ?? '',
        email: authUser.email ?? email.trim().toLowerCase(),
      );
    }
  }

  Future<RegistrationResult> register({
    required String name,
    required String surname,
    required String email,
    required String password,
  }) async {
    final normalizedEmail = email.trim().toLowerCase();
    final response = await _supabase.auth.signUp(
      email: normalizedEmail,
      password: password,
      data: {'name': name.trim(), 'surname': surname.trim()},
    );
    if (response.user == null) {
      throw const AuthException(
        'Не удалось создать аккаунт. Повторите попытку.',
      );
    }
    return RegistrationResult(
      email: normalizedEmail,
      requiresEmailConfirmation: response.session == null,
    );
  }
}

class BmiRecord {
  BmiRecord({
    this.id,
    required this.height,
    required this.weight,
    required this.date,
    this._savedBmi,
    this._savedRecommendation,
  });

  factory BmiRecord.fromJson(Map<String, dynamic> row) => BmiRecord(
    id: row['id'] as String,
    height: (row['height'] as num?)?.toDouble() ?? 0,
    weight: (row['weight'] as num?)?.toDouble() ?? 0,
    date: DateTime.parse(row['created_at'] as String).toLocal(),
    savedBmi: (row['body_mass_index'] as num?)?.toDouble() ?? 0,
    savedRecommendation:
        row['recommendation'] as String? ?? 'Рекомендация не указана',
  );

  final String? id;
  final double? _savedBmi;
  final String? _savedRecommendation;
  final double height;
  final double weight;
  final DateTime date;
  double get bmi => _savedBmi ?? weight / ((height / 100) * (height / 100));

  String get formattedBmi =>
      bmi.toStringAsFixed(2).replaceFirst(RegExp(r'\.?0+$'), '');

  // Интервалы задания без пересечений: <=16; (16,18.5); [18.5,25);
  // [25,30); [30,35); [35,40); >=40. Сравниваем неокруглённый ИМТ.
  String get category {
    if (bmi <= 16) return 'Выраженный дефицит массы тела';
    if (bmi < 18.5) return 'Недостаточная масса тела';
    if (bmi < 25) return 'Норма';
    if (bmi < 30) return 'Избыточная масса тела или предожирение';
    if (bmi < 35) return 'Ожирение';
    if (bmi < 40) return 'Ожирение резкое';
    return 'Очень резкое ожирение';
  }

  String get recommendation {
    if (_savedRecommendation != null) return _savedRecommendation;
    if (bmi <= 16) {
      return 'Выраженный дефицит массы тела. Советуем набрать вес для здоровья.';
    }
    if (bmi < 18.5) {
      return 'Недостаточная масса тела. Рекомендуется увеличить массу тела.';
    }
    if (bmi < 25) {
      return 'Норма. Ваш вес в здоровом диапазоне — поддерживайте его!';
    }
    if (bmi < 30) {
      return 'Избыточная масса тела или предожирение. Желательно снизить вес для улучшения самочувствия.';
    }
    if (bmi < 35) {
      return 'Ожирение. Рекомендуется уменьшить вес под контролем специалиста.';
    }
    if (bmi < 40) {
      return 'Ожирение резкое. Необходимо снижение веса с медицинской поддержкой.';
    }
    return 'Очень резкое ожирение. Требуется срочная коррекция веса под наблюдением врача.';
  }
}

// Integers exactly representable on both Dart VM and Flutter Web, within bigint.
bool isDatabaseMeasurement(double value) =>
    value.isFinite &&
    value > 0 &&
    value <= 9007199254740991 &&
    value == value.truncateToDouble();

double? parsePositiveNumber(String text) {
  final value = double.tryParse(text.trim().replaceAll(',', '.'));
  return value != null && value.isFinite && value > 0 ? value : null;
}
